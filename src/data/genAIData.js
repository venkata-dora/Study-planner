// Items carry a trailing importance marker: '... ⟦5⟧' (1 = niche, 5 = must know).
const RANK_RE = /\s⟦([1-5])⟧$/

export function itemText(item) {
  return String(item).replace(RANK_RE, '')
}

// Clean name for blog generation: no pass symbol, no rank marker.
export function itemTopic(item) {
  return String(item).replace(RANK_RE, '').replace(/^[★◆○]\s*/, '').trim()
}

export function itemRank(item) {
  const m = String(item).match(RANK_RE)
  return m ? Number(m[1]) : null
}

